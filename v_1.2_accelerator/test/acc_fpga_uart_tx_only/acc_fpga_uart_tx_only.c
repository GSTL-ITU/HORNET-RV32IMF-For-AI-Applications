// -------------------------------------------------------------------------
// Accelerator Inference Function
// -------------------------------------------------------------------------
int accel_infer(const volatile float *x) {
    
    // 1. Write Parameters
    ACCEL_LAYER_NUM_REG = NUM_LAYERS; 
    uint32_t layer_configs[8] = {256, 128, 64, 32, NUM_CLASSES, 0, 0, 0}; 
    for (int i = 0; i < 8; i++) {
        ACCEL_LAYER_BASE[i] = layer_configs[i]; 
    }

    // 2. Write Inputs 
    for (int i = 0; i < INPUT_DIM; i++) {
        ACCEL_INPUT_BASE[i] = x[i]; 
    }

    // 3. Start Accelerator safely
    ACCEL_START_REG = 0;
    while (ACCEL_DONE_REG == 1) { } // Ensure it's clear before starting
    
    ACCEL_START_REG = 1; 
    while (ACCEL_DONE_REG == 0) { } // Wait for completion
    ACCEL_START_REG = 0;
    
    // 4. Argmax
    uint8_t best_class = 0;
    float max_val = ACCEL_OUTPUT_BASE[0];

    for (int i = 1; i < NUM_CLASSES; i++) {
        if (ACCEL_OUTPUT_BASE[i] > max_val) {
            max_val = ACCEL_OUTPUT_BASE[i];
            best_class = i;
        }
    }
    
    return best_class;
}

